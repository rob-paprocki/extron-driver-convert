#!/usr/bin/env python3
"""
cs_to_qplug.py - Emit a Q-SYS plugin (.qplug Lua file) for an Extron
scaling-capable matrix switcher, with per-output RS-232 insertion as a
first-class feature.

The reverse half of the Q-SYS <-> Extron bridge the project scoped on
qsys-reader (experiments/qsys/SCOPE.md decision D-Q1). Direction A is
`qplug_to_cs.py`; this is Direction B.

Scope v1, pragmatic rather than general:

- Takes a PluginSpec and emits one .qplug targeting a specific Extron
  DTP3-class CrossPoint switcher. The DTP3 CP 884 is the pilot; the
  CP 42 and 6x2 Series share the same SIS surface and should slot in
  with only a topology change.
- Routing primitives: MatrixTieCommand(In, Out, Tie Type) and the
  OutputTieStatus / MatrixIONameStatus feedback it carries.
- Scaler/audio adjuncts in v1: VideoMute per output, ExecutiveMode,
  GlobalVideoMute, PresetRecall, InputSignalStatus. These are the
  controls the plugin can expose honestly from this one driver's wire
  table; the fuller surface (76 commands) is work for v2.
- RS-232 insertion: for each output, a parallel TcpSocket on a
  user-configurable port (defaults to Extron's convention of
  base-port + output-number). SerialSend[N] on the Q-SYS side writes
  to the socket; SerialReceived[N] accumulates whatever comes back
  from the endpoint behind that DTP output. The exact port mapping
  is site-specific (SIS reference governs it); the plugin exposes
  "Serial Base Port" so the installer can match.

What this does NOT do:

- It does not consult the Extron ControlScript module at emit time.
  Direction B's goal is the inverse of Direction A: the Q-SYS plugin
  speaks Extron's SIS directly, so the module is reference material
  (verifying SIS canonical forms) rather than a source. The pilot
  cites the wire table it is matching but does not take it as input.
- It does not render a GetControlLayout from thin air. A manually
  placed layout block ships with the plugin; a layout synthesiser is
  v2 work.
- It does not sign the output. Q-SYS Designer accepts unsigned
  plugins when the user allows it (SCOPE.md unknowns item 2).
- No bench verification. The pilot's acceptance proxy is parsing the
  generated .qplug back through qplug_wire and asserting the extracted
  send-site templates match the SIS forms the Extron driver uses.

Standard library only.
"""
