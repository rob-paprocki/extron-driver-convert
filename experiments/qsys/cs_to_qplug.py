def _choice_labels(name: str):
    """Return the ordered label list for a _CHOICES entry, whether it's a
    dense "labels" list or a sparse "pairs" list of (sis_int, label)."""
    info = _CHOICES[name]
    if "pairs" in info:
        return [label for _, label in info["pairs"]]
    return info["labels"]


# OutputResolution Pix+Rate split -- derived from _CHOICES["OutputResolution"].
# UI shows two side-by-side dropdowns ("1080p" + "60Hz") instead of one 59-entry
# dropdown ("1080p (60Hz)"); the pair resolves to the sparse SIS int at send
# time via RATE_INDEX.
_RATE_RATES_ORDER = [
    "23.98Hz", "24Hz", "25Hz", "29.97Hz", "30Hz", "50Hz", "59.94Hz", "60Hz",
]


def _derive_rate_split():
    """Return (pix_order, rate_order, rate_index), where:
       pix_order    : resolutions in table order, unique
       rate_order   : rates in a stable canonical order, filtered to those used
       rate_index   : dict mapping (pix, rate) -> sis_int
    """
    pix_order = []
    rates_used = set()
    rate_index = {}
    for sis_int, label in _CHOICES["OutputResolution"]["pairs"]:
        m = re.match(r"^(.+?) \((.+)\)$", label)
        if not m:
            continue
        pix, rate = m.group(1), m.group(2)
        if pix not in pix_order:
            pix_order.append(pix)
        rates_used.add(rate)
        rate_index[(pix, rate)] = sis_int
    rate_order = [r for r in _RATE_RATES_ORDER if r in rates_used]
    return pix_order, rate_order, rate_index


def _lua_choice_list(name: str) -> str:
    """Render a _CHOICES entry's labels as a Lua table literal, one per line
    for readability. Caller handles indentation."""
    return _lua_choice_list_literal(_choice_labels(name))


def _lua_choice_list_literal(labels) -> str:
    """Render any ordered list of strings as a Lua table literal, one per line."""
    return "{\n    " + ",\n    ".join(_lua_str(s) for s in labels) + ",\n  }"


# ---------------------------------------------------------------------------
# Family-mode helpers (shared across emit stages)
# ---------------------------------------------------------------------------

def _is_family(spec: "PluginSpec") -> bool:
    """A family plugin exposes a Model enum property and looks up its I/O
    topology from MODELS at runtime; a single-model plugin has fixed I/O."""
    return bool(spec.models)


def _max_io(spec: "PluginSpec") -> "tuple[int, int]":
    """Return (max_inputs, max_outputs) across every model (for family
    plugins) or (spec.inputs, spec.outputs) (for single-model plugins).
    GetControls uses this for the Count= declarations so EVERY possible
    control exists; the layout and runtime trim to the ACTIVE model.

    Family models hold capability dicts {inputs, outputs, scaled_outputs,
    audio_only, amp_output, sl_io, has_usb}; _max_io reads inputs/outputs."""
    if not _is_family(spec):
        return spec.inputs, spec.outputs
    models = spec.models or {}
    mi = max(m["inputs"] for m in models.values())
    mo = max(m["outputs"] for m in models.values())
    return mi, mo


# ---------------------------------------------------------------------------
# Lua rendering helpers
# ---------------------------------------------------------------------------

def _lua_str(s: str) -> str:
    """Quote a string as a Lua double-quoted literal, with \\r \\n escapes."""
    escaped = (s.replace("\\", "\\\\")
                .replace("\"", "\\\"")
                .replace("\r", "\\r")
                .replace("\n", "\\n")
                .replace("\t", "\\t"))
    return "\"" + escaped + "\""


def _lua_table_inline(d: dict) -> str:
    """Render a flat dict as a Lua inline table literal.

    Keys that look like Lua identifiers go unquoted; everything else is
    bracketed-quoted. Values must already be rendered Lua (strings, numbers,
    booleans, nested tables).
    """
    parts = []
    for k, v in d.items():
        if isinstance(k, str) and re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", k):
            parts.append("%s = %s" % (k, v))
        else:
            parts.append("[%s] = %s" % (_lua_str(str(k)), v))
    return "{ " + ", ".join(parts) + " }"


