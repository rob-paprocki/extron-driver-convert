def _emit_get_pages(spec: PluginSpec) -> str:
    # Tab names and order deliberately match Extron PCS for the DTP3
    # CrossPoint 884. Users accustomed to configuring the device in
    # PCS find their landmarks here: EDID Minder, Input Config,
    # Output Config, Scaler Settings, Ties and Presets, General
    # Settings. RS-232 Insertion is a sub-section of General Settings
    # in PCS; Q-SYS plugin panels have no sub-tabs, so it keeps its
    # own top-level tab when enabled.
    pages = [
        "\"EDID Minder\"",
        "\"Input Config\"",
        "\"Output Config\"",
        "\"Scaler Settings\"",
        "\"Ties and Presets\"",
        "\"General Settings\"",
    ]
    if spec.serial_insertion:
        pages.append("\"RS-232 Insertion\"")
    return "\n".join([
        "function GetPages(props)",
        "  local pages = {}",
        "  for _, name in ipairs({ %s }) do" % ", ".join(pages),
        "    table.insert(pages, { name = name })",
        "  end",
        "  return pages",
        "end",
    ])


