def _emit_rate_split_block() -> str:
    """Render the Pix+Rate split tables: RATE_INDEX (pix->rate->sis_int)
    and RATE_REVERSE (sis_int -> {pix, rate}), plus the ordered pix/rate
    lists Lua uses to snap to the first valid rate when a resolution
    change invalidates the current rate."""
    pix_order, rate_order, rate_index = _derive_rate_split()
    lines = ["  local RATE_PIX_ORDER = { %s }" % ", ".join(_lua_str(p) for p in pix_order)]
    lines.append("  local RATE_RATES_ORDER = { %s }" % ", ".join(_lua_str(r) for r in rate_order))
    lines.append("  local RATE_INDEX = {")
    for pix in pix_order:
        inner = []
        for rate in rate_order:
            v = rate_index.get((pix, rate))
            if v is not None:
                inner.append("[%s] = %d" % (_lua_str(rate), v))
        lines.append("    [%s] = { %s }," % (_lua_str(pix), ", ".join(inner)))
    lines.append("  }")
    lines.append("  local RATE_REVERSE = {")
    for (pix, rate), sis_int in sorted(rate_index.items(), key=lambda kv: kv[1]):
        lines.append("    [%d] = { pix = %s, rate = %s }," % (sis_int, _lua_str(pix), _lua_str(rate)))
    lines.append("  }")
    return "\n".join(lines)


def _emit_choices_block() -> str:
    """Render the CHOICES + CBASE + CSPARSE Lua tables for the runtime.
    CHOICES: ordered label list per enum (for display and dense lookup).
    CBASE:   SIS base offset for dense enums (0 or 1).
    CSPARSE: for enums whose SIS values are non-contiguous (RATE table has
             gaps), label<->int lookup maps in both directions.
    """
    lines = ["  local CHOICES = {"]
    for name in _CHOICES:
        label_lits = ", ".join(_lua_str(s) for s in _choice_labels(name))
        lines.append("    %s = { %s }," % (name, label_lits))
    lines.append("  }")
    lines.append("  local CBASE = {")
    for name, info in _CHOICES.items():
        if "base" in info:
            lines.append("    %s = %d," % (name, info["base"]))
    lines.append("  }")
    lines.append("  local CSPARSE = {")
    for name, info in _CHOICES.items():
        if "pairs" not in info:
            continue
        lines.append("    %s = {" % name)
        lines.append("      labels = {")
        for siv, label in info["pairs"]:
            lines.append("        [%d] = %s," % (siv, _lua_str(label)))
        lines.append("      },")
        lines.append("      byLabel = {")
        for siv, label in info["pairs"]:
            lines.append("        [%s] = %d," % (_lua_str(label), siv))
        lines.append("      },")
        lines.append("    },")
    lines.append("  }")
    return "\n".join(lines)


def _emit_runtime(spec: PluginSpec) -> str:
    # INPUTS/OUTPUTS are now resolved at runtime from the Model property
    # (or DEFAULT_MODEL for single-model plugins), not substituted here.
    body = (RUNTIME_TEMPLATE
            .replace("{{CHOICES_BLOCK}}", _emit_choices_block())
            .replace("{{RATE_SPLIT_BLOCK}}", _emit_rate_split_block()))
    return body


