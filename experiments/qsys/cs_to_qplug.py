def _emit_models_block(spec: PluginSpec) -> str:
    """Top-of-file Lua MODELS table. Each entry carries both topology
    (inputs, outputs) and capabilities (scaled_outputs, audio_only list,
    amp_output number, sl_io number, has_usb bool). GetControlLayout
    and the runtime both look up props["Model"].Value in this table --
    uniform code path whether the plugin is a family (user picks via
    the Model enum property) or a single-model plugin (one entry,
    picked by default)."""
    if _is_family(spec):
        models = spec.models or {}
        default = spec.default_model or next(iter(models))
    else:
        # Single-model plugin: synthesize a 1-entry MODELS so the
        # downstream layout and runtime use the same lookup path.
        # Capabilities default to "no USB, no amp, no SL, all outputs
        # are video, as many scaled outputs as there are outputs" --
        # matches the behaviour of the old plugin before per-model
        # capability awareness was added.
        models = {
            spec.model: {
                "inputs": spec.inputs,
                "outputs": spec.outputs,
                "scaled_outputs": spec.outputs,
                "scaled_min": 1,
                "audio_only": [],
                "amp_output": None,
                "has_amp": False,
                "sl_io": None,
                "has_usb": False,
            }
        }
        default = spec.model
    lines = ["-- Model -> topology + capabilities lookup", "MODELS = {"]
    for name, m in models.items():
        audio_only_lua = "{ %s }" % ", ".join(str(n) for n in m["audio_only"])
        amp = str(m["amp_output"]) if m["amp_output"] is not None else "nil"
        sl = str(m["sl_io"]) if m["sl_io"] is not None else "nil"
        has_usb = "true" if m["has_usb"] else "false"
        # scaled_min defaults to 1 (scaled outputs start at output 1); some
        # families (e.g. DTP CP 108 4K) have scalers only on later outputs
        # (5-8), in which case scaled_min > 1 so the Scaler Settings tab
        # labels rows with the correct output numbers.
        scaled_min = m.get("scaled_min", 1)
        # has_amp is True for IPCP A / IPCP SA / IPCP MA 70 variants that
        # carry a built-in amp but don't expose it as a matrix output
        # (older DTP CrossPoint non-3 generation). Independent of
        # amp_output, which is the output *number* when the amp is
        # addressable through the matrix (DTP3 IPCP A variants).
        has_amp = "true" if m.get("has_amp") or m["amp_output"] is not None else "false"
        lines.append(
            "  [%s] = { inputs = %d, outputs = %d, scaled_outputs = %d, scaled_min = %d, "
            "audio_only = %s, amp_output = %s, has_amp = %s, sl_io = %s, has_usb = %s },"
            % (_lua_str(name), m["inputs"], m["outputs"], m["scaled_outputs"], scaled_min,
               audio_only_lua, amp, has_amp, sl, has_usb))
    lines.append("}")
    lines.append("DEFAULT_MODEL = %s" % _lua_str(default))
    lines.append("")
    lines.append("function _resolveTopology(props)")
    lines.append("  local m = (props and props[\"Model\"] and props[\"Model\"].Value) or DEFAULT_MODEL")
    lines.append("  local t = MODELS[m] or MODELS[DEFAULT_MODEL]")
    lines.append("  return t.inputs, t.outputs")
    lines.append("end")
    lines.append("")
    lines.append("function _resolveCapabilities(props)")
    lines.append("  local m = (props and props[\"Model\"] and props[\"Model\"].Value) or DEFAULT_MODEL")
    lines.append("  return MODELS[m] or MODELS[DEFAULT_MODEL]")
    lines.append("end")
    lines.append("")
    lines.append("-- `isAudioOnly(cap, out)` -> true if output `out` is in the model's")
    lines.append("-- audio-only list. Used by the layout and runtime to skip scaler /")
    lines.append("-- HDCP settings for those outputs and colour-code the matrix header.")
    lines.append("function isAudioOnly(cap, out)")
    lines.append("  if not cap or not cap.audio_only then return false end")
    lines.append("  for _, n in ipairs(cap.audio_only) do if n == out then return true end end")
    lines.append("  return false")
    lines.append("end")
    lines.append("")
    return "\n".join(lines)


def _emit_plugin_info(spec: PluginSpec) -> str:
    bv = spec.build_version or spec.version
    return "\n".join([
        _emit_models_block(spec),
        "PluginInfo = {",
        "  Name = %s,"           % _lua_str(spec.name),
        "  Version = %s,"        % _lua_str(spec.version),
        "  BuildVersion = %s,"   % _lua_str(bv),
        "  Id = %s,"             % _lua_str(spec.plugin_id),
        "  Description = %s,"    % _lua_str(spec.description),
        "  Manufacturer = %s,"   % _lua_str(spec.manufacturer),
        "  Model = %s,"          % _lua_str(spec.model),
        "  Author = %s,"         % _lua_str(spec.author),
        "  Type = Reflect and Reflect.Types.VideoIO or 0,",
        "  IsManaged = true,",
        "}",
        "",
        "function GetColor(props)",
        "  return { 255, 102, 0 }",
        "end",
        "",
        "function GetPrettyName(props)",
        # The canvas label is `<Manufacturer> <ModelName>\n v<buildVersion>`.
        # Two bugs with the previous version: `\\r` in the Python string was
        # literal "backslash r" (not a CR), so _lua_str re-escaped it and
        # Designer rendered the two characters `\r`; and in a family plugin
        # the baked-in spec.model is a generic placeholder ("DTP3 CrossPoint"),
        # not the user's picked variant. Here we read props["Model"].Value
        # when it exists (family mode) and fall back to spec.model otherwise,
        # and use an actual newline so Designer breaks the line correctly.
        "  local model = (props and props[\"Model\"] and props[\"Model\"].Value) or %s" % _lua_str(spec.model),
        "  return %s .. \" \" .. model .. \"\\nv%s\"" % (_lua_str(spec.manufacturer), bv),
        "end",
    ])


def _emit_get_properties(spec: PluginSpec) -> str:
    lines = [
        "function GetProperties()",
        "  local props = {}",
    ]
    if _is_family(spec):
        # Model enum: picking a different model re-runs GetControls and
        # GetControlLayout with the new props value, so the I/O counts and
        # the matrix dimensions update to match. Choices are rendered in
        # insertion order (Python dict preserves it).
        choices = ", ".join(_lua_str(k) for k in (spec.models or {}).keys())
        lines.append("  table.insert(props, { Name = \"Model\", Type = \"enum\", Choices = { %s }, Value = %s })" % (
            choices, _lua_str(spec.default_model or next(iter(spec.models or {})))))
    lines += [
        "  table.insert(props, { Name = \"IP Address\", Type = \"string\", Value = \"192.168.0.100\" })",
        "  table.insert(props, { Name = \"Port\", Type = \"integer\", Min = 1, Max = 65535, Value = %d })" % spec.default_port,
        "  table.insert(props, { Name = \"Password\", Type = \"string\", Value = \"\" })",
    ]
    if spec.serial_insertion:
        lines += [
            "  table.insert(props, { Name = \"Serial Insertion\", Type = \"boolean\", Value = true })",
            "  table.insert(props, { Name = \"Serial Base Port\", Type = \"integer\", Min = 1, Max = 65535, Value = %d })" % spec.serial_base_port_default,
            "  -- Serial insertion opens TcpSocket to Serial Base Port + output number per output.",
            "  -- Verify the base port against the Extron SIS reference for %s before use." % spec.model,
        ]
    lines += [
        "  table.insert(props, { Name = \"Debug\", Type = \"enum\", Choices = {\"None\",\"Tx/Rx\",\"Tx\",\"Rx\"}, Value = \"None\" })",
        "  return props",
        "end",
        "",
        "function RectifyProperties(props)",
        "  return props",
        "end",
    ]
    return "\n".join(lines)


