#!/usr/bin/env python3
"""
mock_sis.py - A pretend Extron DTP3 CP 884 for Q-SYS Designer F6 emulation.

Listens on:
  - a main SIS port (default 23) for the driver's control-plane commands
  - a per-output serial-insertion port (default base + 1..N) for the RS-232
    tunnel channels, where N is the output count

The plugin generated by cs_to_qplug.py opens N+1 TcpSockets; without this
mock, F6 emulation would just show "disconnected" and nothing useful would
run. With it, the plugin's Lua runtime block exchanges real bytes and we
can prove end-to-end wiring from a Q-SYS control pin to the SIS wire.

What this does:
  - Accepts the SIS verbose-mode command and quietly ignores it.
  - Answers input / output name queries (wNmi<n>, / wNmo<n>,) with
    "Camera N" / "Display N" sensible defaults.
  - Answers input-signal poll (0LS\\r) with a bitmask (inputs 1..4 live).
  - Answers executive-mode query (X) with Exe0.
  - Answers video-mute query (w<out>*VMUT) with Vmut<out>*0.
  - Answers tie query (<out>%) with the current internal tie state.
  - Accepts a tie set (<in>*<out>[!$%]) and echoes a verbose OutN InM
    All/Vid/Aud back on every open control connection, as the real
    switcher does.
  - For serial-tunnel ports: echoes "ACK:<bytes>\\r\\n" so the plugin's
    SerialReceived[n] shows the round-trip.

Logs every tx and rx with a timestamp to the chosen log file, so after a
Designer F6 session the file is the evidence trail.

Standard library only.
"""
from __future__ import annotations

import argparse
import datetime
import os
import re
import socket
import socketserver
import sys
import threading
from typing import Optional


LOG_LOCK = threading.Lock()
STATE_LOCK = threading.Lock()

# -------------------------------------------------------------------------
# Device state
# -------------------------------------------------------------------------

NUM_INPUTS = 8
NUM_OUTPUTS = 8

TIES = [0] * (NUM_OUTPUTS + 1)       # TIES[o] = input (0 = none); index 0 unused
TIE_KIND = ["All"] * (NUM_OUTPUTS + 1)
VIDEO_MUTE = [0] * (NUM_OUTPUTS + 1)  # 0 = unmute, 1 = vid mute, 2 = full mute
EXEC_MODE = 0
PRESET_ACTIVE = 0

# Input signal mask: '1' = signal present at that input. 4 live, 4 dark.
SIGNAL_MASK = "11110000"

INPUT_NAMES = ["Camera %d" % i for i in range(1, NUM_INPUTS + 1)]
OUTPUT_NAMES = ["Display %c" % chr(ord("A") + i) for i in range(NUM_OUTPUTS)]


# Every open control connection, so a tie-set broadcasts to everyone
CONTROL_CLIENTS: list = []
CONTROL_CLIENTS_LOCK = threading.Lock()


# -------------------------------------------------------------------------
# Logging
# -------------------------------------------------------------------------

def _ts() -> str:
    return datetime.datetime.now().strftime("%H:%M:%S.%f")[:-3]


def log(f, direction: str, port: int, data: bytes):
    """Append a tx/rx record. Direction is 'tx' (device -> plugin) or 'rx'
    (plugin -> device)."""
    with LOG_LOCK:
        try:
            printable = data.decode("latin-1").encode("unicode_escape").decode("ascii")
        except Exception:
            printable = repr(data)
        f.write("%s %-5s port=%-5d %s\n" % (_ts(), direction, port, printable))
        f.flush()


# -------------------------------------------------------------------------
# SIS command parsing
# -------------------------------------------------------------------------

def _tie_reply(out: int) -> str:
    inp = TIES[out]
    kind = TIE_KIND[out] if inp > 0 else "All"
    return "Out%d In%d %s\r\n" % (out, inp, kind)


def handle_sis_line(buf: bytes) -> list:
    """Given one logical SIS 'thing' from the plugin, return a list of
    reply strings. buf has already been un-escaped (so '\\r' is one byte).

    This parser is minimal - just enough to drive the v1 plugin:
      - 3CV              verbose mode (silent accept)
      - 0LS              input-signal poll -> 'In00 <mask>\\r\\n'
      - X                exec mode query  -> 'Exe<n>\\r\\n'
      - <n>X             exec mode set
      - <n>.             preset recall
      - <o>%             tie query
      - <i>*<o>[!$%]     tie set
      - w<o>*VMUT        video mute query
      - w<o>*<v>VMUT     video mute set
      - wBVMUT family    global video mute
      - wNmi<n>,         input name query
      - wNmo<n>,         output name query
      - wNmi<n>,<name>   input name set
      - wNmo<n>,<name>   output name set
    """
    global EXEC_MODE, PRESET_ACTIVE

    s = buf.decode("latin-1", errors="replace")
    s = s.replace("\r", "").replace("\n", "")
    if not s:
        return []

    replies = []

    # 3CV verbose - silent accept (strip ESC)
    if "\x1b3CV" in s or "\x1B3CV" in s:
        return []

    # 0LS -> signal mask
    if s == "0LS":
        return ["In00 %s\r\n" % SIGNAL_MASK]

    # Executive mode: 'X' query, '<n>X' set
    m = re.match(r"^(\d+)X$", s)
    if m:
        with STATE_LOCK:
            EXEC_MODE = int(m.group(1))
        return ["Exe%d\r\n" % EXEC_MODE]
    if s == "X":
        return ["Exe%d\r\n" % EXEC_MODE]

    # Preset recall '<n>.'
    m = re.match(r"^(\d+)\.$", s)
    if m:
        with STATE_LOCK:
            PRESET_ACTIVE = int(m.group(1))
        return ["Rpr%d\r\n" % PRESET_ACTIVE]

    # Tie query '<o>%'
    m = re.match(r"^(\d+)%$", s)
    if m:
        return [_tie_reply(int(m.group(1)))]

    # Tie set '<in>*<out>[!$%]'
    m = re.match(r"^(\d+)\*(\d+)([!$%])$", s)
    if m:
        inp, out, ch = int(m.group(1)), int(m.group(2)), m.group(3)
        kind = {"!": "All", "%": "Vid", "$": "Aud"}[ch]
        if 1 <= out <= NUM_OUTPUTS:
            with STATE_LOCK:
                TIES[out] = inp
                TIE_KIND[out] = kind
        return [_tie_reply(out)]

    # Video mute query 'w<o>*VMUT'
    m = re.match(r"^w(\d+)\*VMUT$", s)
    if m:
        o = int(m.group(1))
        return ["Vmut%d*%d\r\n" % (o, VIDEO_MUTE[o] if 1 <= o <= NUM_OUTPUTS else 0)]

    # Video mute set 'w<o>*<v>VMUT'
    m = re.match(r"^w(\d+)\*(\d+)VMUT$", s)
    if m:
        o, v = int(m.group(1)), int(m.group(2))
        if 1 <= o <= NUM_OUTPUTS:
            with STATE_LOCK:
                VIDEO_MUTE[o] = v
        return ["Vmut%d*%d\r\n" % (o, v)]

    # Global video mute: 'wB<v>VMUT'
    m = re.match(r"^wB(\d+)VMUT$", s)
    if m:
        v = int(m.group(1))
        with STATE_LOCK:
            for i in range(1, NUM_OUTPUTS + 1):
                VIDEO_MUTE[i] = v
        return ["Vmut00*%d\r\n" % v]

    # Input name query / set
    m = re.match(r"^wNmi(\d+),(.*)$", s)
    if m:
        n, name = int(m.group(1)), m.group(2)
        if name:
            if 1 <= n <= NUM_INPUTS:
                with STATE_LOCK:
                    INPUT_NAMES[n - 1] = name
            return ["Nmi%d,%s\r\n" % (n, name)]
        else:
            return ["Nmi%d,%s\r\n" % (n, INPUT_NAMES[n - 1] if 1 <= n <= NUM_INPUTS else "")]

    # Output name query / set
    m = re.match(r"^wNmo(\d+),(.*)$", s)
    if m:
        n, name = int(m.group(1)), m.group(2)
        if name:
            if 1 <= n <= NUM_OUTPUTS:
                with STATE_LOCK:
                    OUTPUT_NAMES[n - 1] = name
            return ["Nmo%d,%s\r\n" % (n, name)]
        else:
            return ["Nmo%d,%s\r\n" % (n, OUTPUT_NAMES[n - 1] if 1 <= n <= NUM_OUTPUTS else "")]

    # ---- scaling / HDCP / EDID / Flex I/O (v2 plugin surface) ------------
    # AspectRatio: w<in>ASPR query, w<in>*<val>ASPR set -> 'Aspr<in>*<val>\r\n'
    m = re.match(r"^w(\d+)ASPR$", s)
    if m:
        i = int(m.group(1))
        return ["Aspr%d*%d\r\n" % (i, 2)]  # default: Follow
    m = re.match(r"^w(\d+)\*(\d+)ASPR$", s)
    if m:
        return ["Aspr%d*%d\r\n" % (int(m.group(1)), int(m.group(2)))]

    # OutputResolution: w<out>RATE query, w<out>*<val>RATE set -> 'Rate<out>*<val>\r\n'
    m = re.match(r"^w(\d+)RATE$", s)
    if m:
        o = int(m.group(1))
        return ["Rate%d*%d\r\n" % (o, 36)]  # default: 1920x1080 @ 60Hz
    m = re.match(r"^w(\d+)\*(\d+)RATE$", s)
    if m:
        return ["Rate%d*%d\r\n" % (int(m.group(1)), int(m.group(2)))]

    # Freeze: '<o>F' query, '<o>*<v>F' set -> 'Frz<o>*<v>\r\n'
    m = re.match(r"^(\d+)F$", s)
    if m:
        return ["Frz%d*0\r\n" % int(m.group(1))]
    m = re.match(r"^(\d+)\*(\d+)F$", s)
    if m:
        return ["Frz%d*%d\r\n" % (int(m.group(1)), int(m.group(2)))]

    # AutoImage: '1*<o>A' (set) -> 'Imag<o>\r\n'
    m = re.match(r"^\d+\*(\d+)A$", s)
    if m:
        return ["Imag%d\r\n" % int(m.group(1))]

    # Logo: wE<o>*<v>LOGO set -> 'Logo<o>*<v>\r\n'
    m = re.match(r"^wE(\d+)\*(\d+)LOGO$", s)
    if m:
        return ["Logo%d*%d\r\n" % (int(m.group(1)), int(m.group(2)))]

    # ScalerPresetRecall: '2*<o>*<n>.' -> 'Rpr<n>\r\n'
    m = re.match(r"^2\*(\d+)\*(\d+)\.$", s)
    if m:
        return ["Rpr%d\r\n" % int(m.group(2))]

    # HDCP auth: wE<in>HDCP query, wE<in>*<v>HDCP set -> 'HdcpE<in>*<v>\r\n'
    m = re.match(r"^wE(\d+)HDCP$", s)
    if m:
        return ["HdcpE%d*1\r\n" % int(m.group(1))]
    m = re.match(r"^wE(\d+)\*(\d+)HDCP$", s)
    if m:
        return ["HdcpE%d*%d\r\n" % (int(m.group(1)), int(m.group(2)))]

    # HDCP input status: wI<in>HDCP -> 'HdcpI<in>*<v>\r\n'
    m = re.match(r"^wI(\d+)HDCP$", s)
    if m:
        i = int(m.group(1))
        # Default: inputs 1-4 'authenticated' (sync-matching our signal mask), 5-8 '0'
        return ["HdcpI%d*%d\r\n" % (i, 1 if i <= 4 else 0)]

    # HDCP output status: wO<out>HDCP -> 'HdcpO<out>*<v>\r\n'
    m = re.match(r"^wO(\d+)HDCP$", s)
    if m:
        return ["HdcpO%d*1\r\n" % int(m.group(1))]

    # EDID: w<in>EDID query, wA<val>*<in>EDID set -> 'EdidA<in>*<val>\r\n'
    m = re.match(r"^w(\d+)EDID$", s)
    if m:
        i = int(m.group(1))
        return ["EdidA%d*%d\r\n" % (i, 36)]  # default: 1920x1080 @ 60Hz EDID
    m = re.match(r"^wA(\d+)\*(\d+)EDID$", s)
    if m:
        return ["EdidA%d*%d\r\n" % (int(m.group(2)), int(m.group(1)))]

    # InputConnectorType: w<in>ITYP query, w<in>*<val>ITYP set -> 'Ityp<in>*<val>\r\n'
    m = re.match(r"^w(\d+)ITYP$", s)
    if m:
        return ["Ityp%d*5\r\n" % int(m.group(1))]  # default: HDMI
    m = re.match(r"^w(\d+)\*(\d+)ITYP$", s)
    if m:
        return ["Ityp%d*%d\r\n" % (int(m.group(1)), int(m.group(2)))]

    # Flex I/O audio: wG<in>39999AU / wH<in>39999AU / wM<in>39999AU and
    # wG<in>40099AU / wM<in>40099AU, with query and set forms.
    # Replies: 'Ds[gGhHmM]400<nn>*<val>\r\n' or 'Ds[gGhHmM]401<nn>*<val>\r\n'
    m = re.match(r"^w([gGhHmM])(\d+)(39999|40099)(?:\*(-?\d+))?AU$", s)
    if m:
        kind, inp, fam, val = m.group(1), int(m.group(2)), m.group(3), m.group(4)
        fam3 = "400" if fam == "39999" else "401"
        nn = "%02d" % (inp - 1)
        if val is None:
            # Query: return current (defaults)
            if kind.lower() == "m":
                return ["Ds%s%s%s*0\r\n" % (kind, fam3, nn)]
            return ["Ds%s%s%s*0\r\n" % (kind, fam3, nn)]
        return ["Ds%s%s%s*%s\r\n" % (kind, fam3, nn, val)]

    # Unknown -> emit a classic Extron error
    return ["E12\r\n"]


# -------------------------------------------------------------------------
# Control-plane server
# -------------------------------------------------------------------------

class ControlHandler(socketserver.StreamRequestHandler):
    log_file = None  # set via a wrapper

    def handle(self):
        with CONTROL_CLIENTS_LOCK:
            CONTROL_CLIENTS.append(self.wfile)
        try:
            # Extron banner
            banner = ("(c)Copyright 2026 Mock Extron DTP3 CP 884, Fw 1.00\r\n"
                      "Password: \r\n")
            self.wfile.write(banner.encode("latin-1"))
            log(self.log_file, "tx", self.server.server_address[1], banner.encode("latin-1"))
            buf = b""
            while True:
                chunk = self.rfile.read1(1024)
                if not chunk:
                    break
                log(self.log_file, "rx", self.server.server_address[1], chunk)
                buf += chunk
                # Split on \r or \n
                while True:
                    # Split at any \r or \n, keep remainder
                    idx = -1
                    for sep in (b"\r\n", b"\n", b"\r"):
                        j = buf.find(sep)
                        if j != -1 and (idx == -1 or j < idx):
                            idx = j
                    if idx == -1:
                        break
                    line, buf = buf[:idx], buf[idx:]
                    # Advance past the terminator
                    for sep in (b"\r\n", b"\n", b"\r"):
                        if buf.startswith(sep):
                            buf = buf[len(sep):]
                            break
                    replies = handle_sis_line(line)
                    for r in replies:
                        rb = r.encode("latin-1")
                        self.wfile.write(rb)
                        log(self.log_file, "tx", self.server.server_address[1], rb)
                # Terminator-less SIS commands. The plugin can emit any of:
                #   'X' / '<n>X' / '<n>.' / '<n>%' / '<n>F' / '<n>*<m>F' /
                #   '<n>*<m>A' / '<n>*<m><tieChar>' (tieChar in !$%).
                # They often arrive concatenated with no separator. Peel one
                # off the front of buf per iteration until buf is empty or
                # starts with something we do not recognise.
                _SHORT_RES = [
                    re.compile(rb"^\x1b*(\d+)\*(\d+)[!$%FA]"),   # <n>*<m>[!$%FA]
                    re.compile(rb"^\x1b*(\d+)[X.%F]"),            # <n>X / <n>. / <n>% / <n>F
                    re.compile(rb"^\x1b*X"),                      # X alone
                ]
                while buf:
                    one = None
                    for pat in _SHORT_RES:
                        m = pat.match(buf)
                        if m:
                            one = buf[:m.end()]
                            break
                    if one is None:
                        # buf starts with something we do not yet understand;
                        # wait for more bytes (next outer-loop iteration).
                        break
                    replies = handle_sis_line(one)
                    for r in replies:
                        rb = r.encode("latin-1")
                        self.wfile.write(rb)
                        log(self.log_file, "tx", self.server.server_address[1], rb)
                    buf = buf[len(one):]
        except (BrokenPipeError, ConnectionResetError):
            pass
        finally:
            with CONTROL_CLIENTS_LOCK:
                try: CONTROL_CLIENTS.remove(self.wfile)
                except ValueError: pass


# -------------------------------------------------------------------------
# Per-output serial-tunnel server (plain echo + ACK)
# -------------------------------------------------------------------------

class SerialHandler(socketserver.StreamRequestHandler):
    log_file = None
    output_num = 0

    def handle(self):
        try:
            # Immediate hello so Q-SYS SerialReceived shows SOMETHING
            hello = ("ENDPOINT %d READY\r\n" % self.output_num).encode("latin-1")
            self.wfile.write(hello)
            log(self.log_file, "tx", self.server.server_address[1], hello)
            while True:
                chunk = self.rfile.read1(1024)
                if not chunk:
                    break
                log(self.log_file, "rx", self.server.server_address[1], chunk)
                reply = b"ACK:" + chunk.strip() + b"\r\n"
                self.wfile.write(reply)
                log(self.log_file, "tx", self.server.server_address[1], reply)
        except (BrokenPipeError, ConnectionResetError):
            pass


# -------------------------------------------------------------------------
# A threaded TCPServer with SO_REUSEADDR
# -------------------------------------------------------------------------

class ReusingThreadingTCPServer(socketserver.ThreadingTCPServer):
    allow_reuse_address = True
    daemon_threads = True


def _bind_handler(handler_cls, port: int, log_file, extra: Optional[dict] = None):
    cls = type(handler_cls.__name__ + "_bound", (handler_cls,), {})
    cls.log_file = log_file
    if extra:
        for k, v in extra.items():
            setattr(cls, k, v)
    srv = ReusingThreadingTCPServer(("127.0.0.1", port), cls)
    t = threading.Thread(target=srv.serve_forever, daemon=True)
    t.start()
    return srv


def _main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                  formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--control-port", type=int, default=23)
    ap.add_argument("--serial-base", type=int, default=2200,
                    help="serial tunnel ports = base + 1..N")
    ap.add_argument("--outputs", type=int, default=NUM_OUTPUTS)
    ap.add_argument("--log", default=None, help="path to log file (default: stdout)")
    ap.add_argument("--once", action="store_true",
                    help="exit after no connections for 30 seconds idle, for CI; otherwise serve forever")
    args = ap.parse_args(argv)

    log_file = sys.stdout
    if args.log:
        log_file = open(args.log, "w", encoding="utf-8")

    servers = []
    try:
        srv = _bind_handler(ControlHandler, args.control_port, log_file)
        servers.append(srv)
        log_file.write("%s start control port=%d\n" % (_ts(), args.control_port))
    except OSError as e:
        print("could not bind control port %d: %s" % (args.control_port, e), file=sys.stderr)
        return 1

    for n in range(1, args.outputs + 1):
        p = args.serial_base + n
        try:
            srv = _bind_handler(SerialHandler, p, log_file, {"output_num": n})
            servers.append(srv)
            log_file.write("%s start serial  port=%d  output=%d\n" % (_ts(), p, n))
        except OSError as e:
            log_file.write("%s skip serial port=%d: %s\n" % (_ts(), p, e))

    log_file.flush()

    try:
        import time
        while True:
            time.sleep(5)
    except KeyboardInterrupt:
        pass
    finally:
        for s in servers:
            try: s.shutdown()
            except Exception: pass
        if log_file is not sys.stdout:
            log_file.close()
    return 0


if __name__ == "__main__":
    sys.exit(_main())
