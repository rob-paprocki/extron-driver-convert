from extronlib.interface import SerialInterface, EthernetClientInterface
import re
from extronlib.system import Wait, ProgramLog

class DeviceClass:
    def __init__(self):

        self.Unidirectional = 'False'
        self.connectionCounter = 15
        self.DefaultResponseTimeout = 0.3
        self.Subscription = {}
        self.ReceiveData = self.__ReceiveData
        self.__receiveBuffer = b''
        self.__maxBufferSize = 2048
        self.__matchStringDict = {}
        self.counter = 0
        self.connectionFlag = True
        self.initializationChk = True
        self.Debug = False
        self._DeviceID = b'\x00'
        self.Models = {}

        self.Commands = {
            'ConnectionStatus': {'Status': {}},
            'RelayAll': { 'Status': {}},
            'RelayControl': {'Parameters': ['Relay'], 'Status': {}},
            'RelayStatus': { 'Status': {}},
        }
 
        if self.Unidirectional == 'False':
            self.AddMatchString(re.compile(b'\xCA\xB0[\x00-\x80]\x06([\x00\x01]{6})[\x00-\xFF]'), self.__MatchRelayStatus, None)
            self.AddMatchString(re.compile(b'\xCA\x80\xFF\xB6'), self.__MatchError, None)

    @property
    def DeviceID(self):
        return self._DeviceID

    @DeviceID.setter
    def DeviceID(self, value):
        if value == 'Broadcast':
            self._DeviceID = b'\xFE'
        elif 0 <= int(value) <= 128:
            self._DeviceID = bytes([int(value)])
        else:
            self.Error(['Invalid Device ID Parameter.'])

    def SetRelayAll(self, value, qualifier):

        ValueStateValues = {
            'On' : b'\xFF\x01',
            'Off': b'\x00\x02'
        }

        if value in ValueStateValues:
            RelayAllCmdString = b''.join([b'\xCA\x20', self._DeviceID, b'\x19\x03\xFF', ValueStateValues[value], b'\xAC'])
            self.__SetHelper('RelayAll', RelayAllCmdString, value, qualifier)
        else:
            self.Discard('Invalid Command for SetRelayAll')

    def SetRelayControl(self, value, qualifier):

        ValueStateValues = {
            'On' : b'\x01',
            'Off': b'\x00'
        }

        if value in ValueStateValues and 1 <= int(qualifier['Relay']) <= 6:
            RelayControlCmdString = b''.join([b'\xCA\x20', self._DeviceID, b'\x18\x02', bytes([int(qualifier['Relay'])]), ValueStateValues[value], b'\xAC'])
            self.__SetHelper('RelayControl', RelayControlCmdString, value, qualifier)
        else:
            self.Discard('Invalid Command for SetRelayControl')

    def UpdateRelayStatus(self, value, qualifier):

        RelayStatusCmdString = b''.join([b'\xCA\x20', self._DeviceID, b'\x20\x01\x01\xAC'])
        self.__UpdateHelper('RelayStatus', RelayStatusCmdString, value, qualifier)

    def __MatchRelayStatus(self, match, tag):

        ValueStateValues = {
            '\x01': 'On',
            '\x00': 'Off'
        }

        values = match.group(1).decode()
        for value in enumerate(values):
            self.WriteStatus('RelayControl', ValueStateValues[value[1]], {'Relay': str(value[0]+1)})

    def __SetHelper(self, command, commandstring, value, qualifier):

        self.Debug = True
        self.Send(commandstring)

    def __UpdateHelper(self, command, commandstring, value, qualifier):

        if self.Unidirectional == 'True' or self._DeviceID == b'\xFE':
            self.Discard('Inappropriate Command ' + command)
        else:
            if self.initializationChk:
                self.OnConnected()
                self.initializationChk = False

            self.counter = self.counter + 1
            if self.counter > self.connectionCounter and self.connectionFlag:
                self.OnDisconnected()
                
            self.Send(commandstring)

    def __MatchError(self, match, tag):
        self.counter = 0
        self.Error(['Command has an error.'])

    def OnConnected(self):
        self.connectionFlag = True
        self.WriteStatus('ConnectionStatus', 'Connected')
        self.counter = 0

    def OnDisconnected(self):
        self.WriteStatus('ConnectionStatus', 'Disconnected')
        self.connectionFlag = False

