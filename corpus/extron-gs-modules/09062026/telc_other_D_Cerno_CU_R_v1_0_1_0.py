class DeviceClass:
    def __init__(self):

        self.Unidirectional = 'False'
        self.Subscription = {}
        self.ReceiveData = self.__ReceiveData
        self.__receiveBuffer = b''
        self.__maxBufferSize = 2048
        self.__matchStringDict = {}
        self.Debug = False
        self.Models = {}

        self.Commands = {
            'ActiveMicrophones': {'Parameters': ['Serial Code'], 'Status': {}},
            'MicrophoneStatus': {'Parameters': ['Serial Code'], 'Status': {}},
            'RequestedMicrophones': {'Parameters': ['Serial Code'], 'Status': {}},
        }

        if self.Unidirectional == 'False':
            self.AddMatchString(re.compile(b'\{\"serial\":\"([0-9A-Fa-f]{8})\",\"status\":([01248]),\"totalMicOn\":([0-8]),\"totalMicReq\":([0-8])\}'), self.__MatchMicrophoneStatus, None)

    def __MatchMicrophoneStatus(self, match, tag):

        states = {
            '0': 'Off',
            '1': 'On',
            '2': 'Request',
            '4': 'Next In Line',
            '8': 'Prior'
        }

        serial_code = match.group(1).decode()
        status = states[match.group(2).decode()]
        active_mics = match.group(3).decode()
        requested_mics = match.group(4).decode()

        self.WriteStatus('ActiveMicrophones', active_mics, {'Serial Code': serial_code})
        self.WriteStatus('MicrophoneStatus', status, {'Serial Code': serial_code})
        self.WriteStatus('RequestedMicrophones', requested_mics, {'Serial Code': serial_code})

    def __SetHelper(self, command, commandstring, value, qualifier):

        self.Debug = True
        self.Send(commandstring)

