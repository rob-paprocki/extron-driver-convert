from extronlib.interface import SerialInterface, EthernetClientInterface
from extronlib.system import Wait, ProgramLog
import re

class DeviceClass:
    def __init__(self):

        self.Unidirectional = 'False'
        self.connectionCounter = 15
        self.DefaultResponseTimeout = 0.3
        self.Subscription = {}
        self.ReceiveData = self.__ReceiveData
        self.__receiveBuffer = b''
        self.__maxBufferSize = 10240
        self.__matchStringDict = {}
        self.counter = 0
        self.connectionFlag = True
        self.initializationChk = True
        self.Debug = False
        self.deviceUsername = None
        self.devicePassword = None
        self.Models = {}

        self.Commands = {
            'ConnectionStatus': {'Status': {}},
            'DeviceState': { 'Status': {}},
            'RecallLayout': {'Parameters':['Scenario Name'], 'Status': {}},
            'Take': {'Parameters':['Window ID','Input ID'], 'Status': {}},
            'TakeCloseAll': { 'Status': {}}
        }

        self.Authenticated = False

        if self.Unidirectional == 'False':
            self.AddMatchString(re.compile(b'<device_info>[\S\s]*?<state>(.*?)</state>[\S\s]*?</device_info>'), self.__MatchDeviceState, None)
            self.AddMatchString(re.compile(b'<error request=\"(.*)\"[\S\s]*?<message>(.*?)</message>[\S\s]*?</error>'), self.__MatchError, None)
            self.AddMatchString(re.compile(b'<setup name=\".*?\" admin[\S\s]*?</setup>'), self.__MatchLogin, None)

    def __MatchLogin(self, match, tag):

        self.Authenticated = True

    def SetLogin(self, value, qualifier):

        self.Send('<setup version="1.x"><username>{0}</username><password>{1}</password><needack>Yes</needack></setup>'.format(self.deviceUsername, self.devicePassword))

    def UpdateDeviceState(self, value, qualifier):

        DeviceStateCmdString = '<query_device_info />'
        self.__UpdateHelper('DeviceState', DeviceStateCmdString, value, qualifier)

    def __MatchDeviceState(self, match, tag):

        value = match.group(1).decode()
        self.WriteStatus('DeviceState', value, None)

    def SetRecallLayout(self, value, qualifier):

        if qualifier['Scenario Name']:
            RecallLayoutCmdString = '<recall_layout usergroup="Admin" scenario_name="{}" id="None" advance="Yes" needack="Yes"/>'.format(qualifier['Scenario Name'])
            self.__SetHelper('RecallLayout', RecallLayoutCmdString, value, qualifier)
        else:
            self.Discard('Invalid Command for SetRecallLayout')

    def SetTake(self, value, qualifier):

        if qualifier['Window ID'] and qualifier['Input ID']:
            TakeCmdString = '<take><window id="{0}" input_id="{1}" /></take>'.format(qualifier['Window ID'], qualifier['Input ID'])
            self.__SetHelper('Take', TakeCmdString, value, qualifier)

    def SetTakeCloseAll(self, value, qualifier):

        TakeCloseAllCmdString = '<take_close_all needack="Yes" />'
        self.__SetHelper('TakeCloseAll', TakeCloseAllCmdString, value, qualifier)

    def __SetHelper(self, command, commandstring, value, qualifier):

        self.Debug = True

        if self.Authenticated == True:
            self.Send(commandstring)
        else:
            self.SetLogin(None, None)

    def __UpdateHelper(self, command, commandstring, value, qualifier):

        if self.Authenticated == True:
            if self.initializationChk:
                self.OnConnected()
                self.initializationChk = False

            self.counter = self.counter + 1
            if self.counter > self.connectionCounter and self.connectionFlag:
                self.OnDisconnected()

            self.Send(commandstring)
        else:
            self.SetLogin(None, None)

    def __MatchError(self, match, tag):

        self.counter = 0

        self.Error(['Error: {0}, {1}'.format(match.group(1).decode(), match.group(2).decode())])

    def OnConnected(self):

        self.connectionFlag = True
        self.WriteStatus('ConnectionStatus', 'Connected')
        self.counter = 0

    def OnDisconnected(self):

        self.WriteStatus('ConnectionStatus', 'Disconnected')
        self.connectionFlag = False

        self.Authenticated = False

