from extronlib.interface import SerialInterface, EthernetClientInterface
from extronlib.system import Wait, ProgramLog
import re


class DeviceClass:
    def __init__(self):

        self.Subscription = {}
        self.ReceiveData = self.__ReceiveData
        self.__receiveBuffer = b''
        self.__maxBufferSize = 2048
        self.__matchStringDict = {}
        self.Debug = False
        self.Models = {}

        self.Commands = {
            'EventPressed': {'Parameters': ['Event Name'], 'Status': {}},
            }

        self.AddMatchString(re.compile(b'([\S ]+)'), self.__MatchEventPressed, None)

    def __MatchEventPressed(self, match, tag):
        eventName = match.group(1).decode()
        self.WriteStatus('EventPressed', 'Pressed', {'Event Name': eventName})

        @Wait(.5)
        def ResetState():
            self.WriteStatus('EventPressed', 'No State', {'Event Name': eventName})

    def __SetHelper(self, command, commandstring, value, qualifier):
        self.Debug = True
        pass

    def __MatchError(self, match, tag):
        self.counter = 0

