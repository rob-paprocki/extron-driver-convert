from extronlib.interface import SerialInterface, EthernetClientInterface
from re import compile, search
from extronlib.system import Wait, ProgramLog

class DeviceClass:
    def __init__(self):

        self.Unidirectional = 'False'
        self.connectionCounter = 15
        self.DefaultResponseTimeout = 0.3
        self.Subscription = {}
        self.ReceiveData = self.__ReceiveData
        self.__receiveBuffer = b''
        self.__maxBufferSize = 2048
        self.__matchStringDict = {}
        self.counter = 0
        self.connectionFlag = True
        self.initializationChk = True
        self.Debug = False
        self._MotorAddress= b'00'
        self.Models = {}

        self.Commands = {
            'ConnectionStatus': {'Status': {}},
            'MotorMovement': { 'Status': {}},
            'MotorPosition': { 'Status': {}},
        }

        motor_pos_regex = b''.join([b'RI?SP [0-9a-f]{2}', br' 04 45 (\d{1,3})\r'])
                        
        if self.Unidirectional == 'False':
            self.AddMatchString(compile(motor_pos_regex), self.__MatchMotorPosition, None)
    @property
    def MotorAddress(self):
        return self._MotorAddress

    @MotorAddress.setter
    def MotorAddress(self, value):
        if 0 <= int(value) <= 255:
            self._MotorAddress= '{:02X}'.format(int(value)).encode(encoding='iso-8859-1')

    def SetMotorMovement(self, value, qualifier):

        ValueStateValues = {
            'Down': b'04',
            'Up':   b'05',
            'Stop': b'03',
        }

        MotorMovementCmdString = b''.join([b'CMD ', self.MotorAddress, b' 04 ', ValueStateValues[value], b'\r'])
        self.__SetHelper('MotorMovement', MotorMovementCmdString, value, qualifier)
    def UpdateMotorPosition(self, value, qualifier):


        MotorPositionCmdString = b''.join([b'CMD ', self.MotorAddress, b' 04 45\r'])
        self.__UpdateHelper('MotorPosition', MotorPositionCmdString, value, qualifier)

    def __MatchMotorPosition(self, match, tag):

        ValueStateConstraints = {
            'Min': 0,
            'Max': 255,
        }


        value = int(match.group(1).decode())
        if ValueStateConstraints['Min'] <= value <= ValueStateConstraints['Max']:
            self.WriteStatus('MotorPosition', value, None)
        else:
            self.Error(['Motor Position Update: Invalid/unexpected response'])

    def __SetHelper(self, command, commandstring, value, qualifier):
        self.Debug = True



        self.Send(commandstring)

    def __UpdateHelper(self, command, commandstring, value, qualifier):

        if self.Unidirectional == 'True':
            self.Discard('Inappropriate Command ' + command)
        else:
            if self.initializationChk:
                self.OnConnected()
                self.initializationChk = False

            self.counter = self.counter + 1
            if self.counter > self.connectionCounter and self.connectionFlag:
                self.OnDisconnected()

            self.Send(commandstring)

    def OnConnected(self):
        self.connectionFlag = True
        self.WriteStatus('ConnectionStatus', 'Connected')
        self.counter = 0

    def OnDisconnected(self):
        self.WriteStatus('ConnectionStatus', 'Disconnected')
        self.connectionFlag = False

