from extronlib.interface import SerialInterface, EthernetClientInterface

class DeviceClass:

    def __init__(self):

        self.Unidirectional = 'False'
        self.connectionCounter = 15
        self.DefaultResponseTimeout = 0.3
        self._compile_list = {}
        self.Subscription = {}
        self.counter = 0
        self.connectionFlag = True
        self.initializationChk = True
        self.Debug = False
        self.Models = {}

        self.Commands = {
            'ConnectionStatus': {'Status': {}},
            'ActivePowerStatus': {'Status': {}},
            'Power': {'Parameters': ['Port'], 'Status': {}},
            'Reset': {'Parameters': ['Port'], 'Status': {}},
        }

    def UpdateActivePowerStatus(self, value, qualifier):

        ActivePowerStatusCmdString = 'linesensor\r1 1 value show\rback\r'
        res = self.__UpdateHelper('ActivePowerStatus', ActivePowerStatusCmdString, value, qualifier)
        if res:
            try:
                value = int(res.split('>')[-1])
                self.WriteStatus('ActivePowerStatus', value, qualifier)
            except (KeyError, IndexError):
                self.Error(['Update Active Power Status: Invalid/unexpected response'])

    def SetPower(self, value, qualifier):

        PortStates = ['1', '2', '3', '4']

        ValueStateValues = {
            'On': '1',
            'Off': '0'
        }

        port_no = qualifier['Port']
        if port_no in PortStates:
            PowerCmdString = 'port\r{} state set {}\rback\r'.format(port_no, ValueStateValues[value])
            self.__SetHelper('Power', PowerCmdString, value, qualifier)
        else:
            self.Discard('Invalid Command for SetPower')

    def UpdatePower(self, value, qualifier):

        ValueStateValues = {
            'ON': 'On',
            'OFF': 'Off'
        }

        PortStates = ['1', '2', '3', '4']

        port_no = qualifier['Port']
        if port_no in PortStates:
            PowerCmdString = 'port\r{} state show\rback\r'.format(port_no)
            res = self.__UpdateHelper('Power', PowerCmdString, value, qualifier)
            if res:
                try:
                    value = ValueStateValues[res[5:-1]]
                    self.WriteStatus('Power', value, qualifier)
                except (KeyError, IndexError):
                    self.Error(['Update Power: Invalid/unexpected response'])
        else:
            self.Discard('Invalid Command for UpdatePower')

    def SetReset(self, value, qualifier):

        PortStates = ['1', '2', '3', '4']

        port_no = qualifier['Port']
        if port_no in PortStates:
            ResetCmdString = 'port\r{} reset\rback\r'.format(port_no)
            self.__SetHelper('Reset', ResetCmdString, value, qualifier)
        else:
            self.Discard('Invalid Command for SetReset')

    def __CheckResponseForErrors(self, sourceCmdName, response):

        if 'ERR' in response:
            self.Error(['Error occurred with command: {0}'.format(sourceCmdName)])
            response = ''
        return response

    def __SetHelper(self, command, commandstring, value, qualifier):
        self.Debug = True

        if self.Unidirectional == 'True':
            self.Send(commandstring)
        else:
            res = self.SendAndWait(commandstring, self.DefaultResponseTimeout, deliTag=b'\r')
            if not res:
                self.Error(['Set {}: No response received'.format(command)])
            else:
                res = self.__CheckResponseForErrors(command, res.decode())

    def __UpdateHelper(self, command, commandstring, value, qualifier):

        if self.Unidirectional == 'True':
            self.Discard('Inappropriate Command ' + command)
            return ''
        else:
            if self.initializationChk:
                self.OnConnected()
                self.initializationChk = False

            self.counter = self.counter + 1
            if self.counter > self.connectionCounter and self.connectionFlag:
                self.OnDisconnected()

            res = self.SendAndWait(commandstring, self.DefaultResponseTimeout, deliTag=b'\r')
            if not res:
                return ''
            else:
                return self.__CheckResponseForErrors(command, res.decode())

    def OnConnected(self):
        self.connectionFlag = True
        self.WriteStatus('ConnectionStatus', 'Connected')
        self.counter = 0

    def OnDisconnected(self):
        self.WriteStatus('ConnectionStatus', 'Disconnected')
        self.connectionFlag = False

