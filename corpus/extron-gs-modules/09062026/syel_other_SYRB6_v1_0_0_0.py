from extronlib.interface import SerialInterface, EthernetClientInterface
import re
class DeviceClass:

    def __init__(self):

        self.Unidirectional = 'False'
        self.connectionCounter = 15
        self.DefaultResponseTimeout = 0.3
        self._compile_list = {}
        self.Subscription = {}
        self.ReceiveData = self.__ReceiveData
        self._ReceiveBuffer = b''
        self.counter = 0
        self.connectionFlag = True
        self.initializationChk = True
        self.Debug = False
        self.Models = {}

        self.Commands = {
            'ConnectionStatus': {'Status': {}},
            'Relay': {'Parameters':['Number'], 'Status': {}},
            }

        if self.Unidirectional == 'False':
            self.AddMatchString(re.compile(b'\x52\x45\x4C\x41\x59\x20([\x31-\x36])\x3D\x4F(\x4E|\x46\x46)\x0D'), self.__MatchRelay, None)

    def SetRelay(self, value, qualifier):

        NumberStates = {
            '1' : b'\x31', 
            '2' : b'\x32', 
            '3' : b'\x33', 
            '4' : b'\x34', 
            '5' : b'\x35', 
            '6' : b'\x36'
        }

        ValueStateValues = {
            'On'  : b'\x31\x0D', 
            'Off' : b'\x30\x0D'
        }

        number = qualifier['Number']
        if number in NumberStates:
            RelayCmdString = b''.join([b'\x52\x4C\x59', NumberStates[number], b'\x3D', ValueStateValues[value]])
            self.__SetHelper('Relay', RelayCmdString, value, qualifier)
        else:
            print('Invalid Command for SetRelay')

    def UpdateRelay(self, value, qualifier):

        NumberStates = {
            '1' : b'\x31', 
            '2' : b'\x32', 
            '3' : b'\x33', 
            '4' : b'\x34', 
            '5' : b'\x35', 
            '6' : b'\x36'
        }
        
        number = qualifier['Number']
        if number in NumberStates:
            RelayCmdString = b''.join([b'\x52\x4C\x59', NumberStates[number], b'\x3F'])
            self.__UpdateHelper('Relay', RelayCmdString, value, qualifier)
        else:
            print('Invalid Command for UpdateRelay')

    def __MatchRelay(self, match, tag):

        NumberStates = {
            '\x31' : '1', 
            '\x32' : '2', 
            '\x33' : '3', 
            '\x34' : '4', 
            '\x35' : '5', 
            '\x36' : '6'
        }

        ValueStateValues = {
            '\x4E'     : 'On', 
            '\x46\x46' : 'Off'
        }

        qualifier = {}
        qualifier['Number'] = NumberStates[match.group(1).decode()]
        value = ValueStateValues[match.group(2).decode()]
        self.WriteStatus('Relay', value, qualifier)

    def __SetHelper(self, command, commandstring, value, qualifier):
        self.Debug = True
        self.Send(commandstring)

    def __UpdateHelper(self, command, commandstring, value, qualifier):

        if self.Unidirectional == 'True':
            print('Inappropriate Command ', command)
        else:

            if self.initializationChk:
                self.OnConnected()
                self.initializationChk = False

            self.counter = self.counter + 1
            if self.counter > self.connectionCounter and self.connectionFlag:
                self.OnDisconnected()

            self.Send(commandstring)

    def OnConnected(self):
        self.connectionFlag = True
        self.WriteStatus('ConnectionStatus', 'Connected')
        self.counter = 0

    def OnDisconnected(self):
        self.WriteStatus('ConnectionStatus', 'Disconnected')
        self.connectionFlag = False

