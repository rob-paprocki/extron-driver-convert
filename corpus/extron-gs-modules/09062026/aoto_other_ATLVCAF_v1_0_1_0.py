from extronlib.interface import SerialInterface, EthernetClientInterface
import re

class DeviceClass:

    def __init__(self):

        self.Unidirectional = 'False'
        self.connectionCounter = 15
        self.Subscription = {}
        self.ReceiveData = self.__ReceiveData
        self.__receiveBuffer = b''
        self.__maxBufferSize = 2048
        self.__matchStringDict = {}
        self.counter = 0
        self.connectionFlag = True
        self.initializationChk = True
        self.Debug = False
        self.Models = {}
        self._CollectionCard = b'\xFD' # Data1

        self.Commands = {
            'ConnectionStatus': {'Status': {}},
            'DVIDataStatus': {'Status': {}},
            'NetPortSend': {'Status': {}},
            'NetPortStatus': {'Parameters': ['NetPort'], 'Status': {}},
        }

        if self.Unidirectional == 'False':
            self.AddMatchString(re.compile(b'\x55\x55\x12\x34\x00\x03[\xFE\xFD]\x00\x00\x00\x00\x77\x03([\x00\x01])([\x00-\xFF])'), self.__MatchDVIDataStatus, None)
            self.AddMatchString(re.compile(b'\x55\x55\x12\x34\x00([\x03\x0B])[\xFE\xFD]\x00\x00\x00\x00\xAA'), self.__MatchError, None)

    @property
    def CollectionCard(self):
        return self._CollectionCard

    @CollectionCard.setter
    def CollectionCard(self, value):
        try:
            self._CollectionCard = {
                'Data1': b'\xFE',
                'Data2': b'\xFD'
            }[value]
        except KeyError:
            print('invalid ConnectionCard value. Options are Data1 or Data2')
        self._CollectionCard = value

    def checkSum(self, value):

        cks = 0
        for i in value:
            cks = cks ^ i
        return bytes([cks])

    def UpdateDVIDataStatus(self, value, qualifier):

        cks = self.checkSum(b''.join([self._CollectionCard, b'\x03\x01']))
        CmdString = b''.join([b'\x55\x55\x12\x34', self._CollectionCard,
                                           b'\x03\x00\x00\x00\x01\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00', cks])

        self.__UpdateHelper('DVIDataStatus', CmdString, value, qualifier)

    def __MatchDVIDataStatus(self, match, tag):

        ValueStateValues = {
            1: 'Received',
            0: 'Not Received'
        }

        value = ValueStateValues[ord(match.group(1))]
        self.WriteStatus('DVIDataStatus', value, None)

        count, netports = 0, ord(match.group(2))
        for n in [2, 32]:
            if (netports & n) == 0:
                self.WriteStatus('NetPortStatus', 'Valid', {'NetPort': 'P{}'.format(count)})
            else:
                self.WriteStatus('NetPortStatus', 'Invalid', {'NetPort': 'P{}'.format(count)})
            count += 1

    def SetNetPortSend(self, value, qualifier):

        ValueStateValues = {
            'All': b'\x00\x00\x00\x00',
            'P0': b'\x01\x00\x01\x01',
            'P1': b'\x01\x01\x01\x00'
        }

        cmdString = b''.join([self._CollectionCard, b'\x0B', ValueStateValues[value]])
        NetPortSendCmdString = b''.join([cmdString, b'\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00', self.checkSum(cmdString)])
        self.__SetHelper('NetPortSend', NetPortSendCmdString, value, qualifier)

    def UpdateNetPortStatus(self, value, qualifier):

        cks = self.checkSum(b''.join([self._CollectionCard, b'\x03\x01']))
        CmdString = b''.join([b'\x55\x55\x12\x34', self._CollectionCard,
                                           b'\x03\x00\x00\x00\x01\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00', cks])

        self.__UpdateHelper('NetPortStatus', CmdString, value, qualifier)

    def __SetHelper(self, command, commandstring, value, qualifier):
        self.Debug = True

        self.Send(commandstring)

    def __UpdateHelper(self, command, commandstring, value, qualifier):

        if self.Unidirectional == 'True':
            self.Discard('Inappropriate Command ' + command)
        else:
            
            if self.initializationChk:
                self.OnConnected()
                self.initializationChk = False

            self.counter = self.counter + 1
            if self.counter > self.connectionCounter and self.connectionFlag:
                self.OnDisconnected()

            self.Send(commandstring)

    def __MatchError(self, match, tag):
        self.counter = 0

        command = {
            3: 'DVIDataStatus',
            11: 'NetPortSend'
        }[int(match.group(1))]

        self.Error(['{}: Error'.format(command)])

    def OnConnected(self):
        self.connectionFlag = True
        self.WriteStatus('ConnectionStatus', 'Connected')
        self.counter = 0

    def OnDisconnected(self):
        self.WriteStatus('ConnectionStatus', 'Disconnected')
        self.connectionFlag = False

