from extronlib.interface import SerialInterface, EthernetClientInterface
import re
from extronlib.system import Wait, ProgramLog


class DeviceClass:

    def __init__(self):

        self.Unidirectional = 'False'
        self.connectionCounter = 15
        self.DefaultResponseTimeout = 0.3
        self.Subscription = {}
        self.ReceiveData = self.__ReceiveData
        self.__receiveBuffer = b''
        self.__maxBufferSize = 2048
        self.__matchStringDict = {}
        self.counter = 0
        self.connectionFlag = True
        self.initializationChk = True
        self.Debug = False
        self.Models = {}
        self.deviceUsername = 'admin'
        self.devicePassword = 'Connect'
        self._ModuleID = 1

        self.Commands = {
            'ConnectionStatus': {'Status': {}},
            'Control': {'Status': {}},
            'DeviceStatus': {'Status': {}},
        }

        if self.Unidirectional == 'False':
            self.AddMatchString(re.compile(b'150,1,([1-8]),([0-9]{1,2})\r\n'), self.__MatchDeviceStatus, None)
            self.AddMatchString(re.compile(b'Username:'), self.__MatchLoginAdmin, None)
            self.AddMatchString(re.compile(b'Password:'), self.__MatchLoginPass, None)

    @property
    def ModuleID(self):
        return self._ModuleID

    @ModuleID.setter
    def ModuleID(self, value):
        if value == 'Broadcast':
            self._ModuleID = 0
        elif 1 <= int(value) <= 8:
            self._ModuleID = int(value)
        else:
            print('Invalid ModuleID, range is from 1 to 8 and Broadcast')
    
    def __MatchLoginPass(self, match, tag):
        if self.deviceUsername:
            self.Send('{0}\r\n'.format(self.deviceUsername))
        else:
            self.MissingCredentialsLog('Username')

    def __MatchLoginAdmin(self, match, tag):
        if self.devicePassword:
            self.Send('{0}\r\n'.format(self.devicePassword))
        else:
            self.MissingCredentialsLog('Password')
            
    def SetControl(self, value, qualifier):

        Ctl_Values = {
            'Up': '30',
            'Down': '33',
            'Partial 1': '31',
            'Partial 2': '32',
            'Stop': '36',
        }

        CmdString = '{0} {1}\r\n'.format(Ctl_Values[value], self._ModuleID)
        self.__SetHelper('Control', CmdString, value, qualifier)

    def UpdateDeviceStatus(self, value, qualifier):

        CmdString = '050\r\n'
        self.__UpdateHelper('DeviceStatus', CmdString, value, qualifier)

    def __MatchDeviceStatus(self, match, tag):

        Device_Values = {
            '0': 'Moving Top',
            '1': 'Moving Bottom',
            '2': 'Moving Partial 1',
            '3': 'Moving Partial 2',
            '4': 'Moving Partial Top',
            '5': 'Moving Partial Bottom',
            '6': 'At Top',
            '7': 'At Bottom',
            '8': 'At Partial 1',
            '9': 'At Partial 2',
            '10': 'Manual Stopped',
            '11': 'Error',
            '12': 'Spare',
            '13': 'Fail Timeout',
            '14': 'Fail Current',
            '15': 'Rattle',
            '16': 'At Partial Top',
            '17': 'At Partial Bottom',
        }

        status = Device_Values[match.group(2).decode()]
        self.WriteStatus('DeviceStatus', status, None)

    ####################################
    def __SetHelper(self, command, commandstring, value, qualifier):
        self.Debug = True

        self.Send(commandstring)

    def __UpdateHelper(self, command, commandstring, value, qualifier):

        if self.Unidirectional == 'True' or self._ModuleID == 0:
            self.Discard('Inappropriate Command ' + command)
        else:
            if self.initializationChk:
                self.OnConnected()
                self.initializationChk = False

            self.counter = self.counter + 1
            if self.counter > self.connectionCounter and self.connectionFlag:
                self.OnDisconnected()

            self.Send(commandstring)

    def OnConnected(self):
        self.connectionFlag = True
        self.WriteStatus('ConnectionStatus', 'Connected')
        self.counter = 0

    def OnDisconnected(self):
        self.WriteStatus('ConnectionStatus', 'Disconnected')
        self.connectionFlag = False

